import { mdTable, toCsv } from "../../shared/table.ts";
import { type Issue, type Role, RULE_TITLES } from "./check.ts";

export function toMarkdown(res: { issues: Issue[]; roles: Record<string, Role>; rows: number }, title = "\"Valid but wrong\" report check"): string {
  const { issues, roles, rows } = res;
  const errors = issues.filter((i) => i.severity === "error");
  const badRows = new Set(errors.map((i) => i.row)).size;
  const byRule: Record<string, Issue[]> = {};
  for (const i of issues) (byRule[i.rule] ??= []).push(i);
  const out = [
    `# ${title}`, "",
    `**${rows.toLocaleString("en-US")} rows checked:** ${errors.length} errors on ${badRows} row(s) (${rows ? ((badRows / rows) * 100).toFixed(1) : 0}%), ${issues.length - errors.length} warnings.`, "",
    "**Columns recognised:** " + Object.entries(roles).filter(([, r]) => r !== "other").map(([c, r]) => `${c} → ${r}`).join(", "), "",
  ];
  if (Object.keys(byRule).length) {
    out.push("## Summary", "", mdTable(["Issue", "Severity", "Count", "Example"], Object.entries(byRule).sort((a, b) => b[1].length - a[1].length).map(([r, l]) => [RULE_TITLES[r] ?? r, l[0].severity, l.length, `row ${l[0].row}, ${l[0].column}: ${l[0].value}`])), "");
    out.push("## First 50 issues", "", mdTable(["Row", "Column", "Value", "Issue", "Detail"], issues.sort((a, b) => a.row - b.row).slice(0, 50).map((i) => [i.row, i.column, i.value, RULE_TITLES[i.rule] ?? i.rule, i.message])), "");
  } else out.push("No issues found by these checks.", "");
  out.push("_Generated by Hyniqe Hub · \"Valid but wrong\" Report Checker. Runs locally. These are plausibility checks on top of, not instead of, the regulator's validation rules._");
  return out.join("\n") + "\n";
}

export function toIssuesCsv(issues: Issue[]): string {
  return toCsv(issues as unknown as Record<string, unknown>[], ["row", "column", "value", "rule", "severity", "message"]);
}
