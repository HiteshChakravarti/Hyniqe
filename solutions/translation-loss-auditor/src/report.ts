import { mdTable, toCsv } from "../../shared/table.ts";
import { type Finding, verdict } from "./audit.ts";

export interface PairResult { name: string; uetr: string; findings: Finding[] }
const ICON = { CRITICAL: "🔴", "DATA LOST": "🟠", MINOR: "🟡", CLEAN: "🟢" } as const;

export function toMarkdown(pairs: PairResult[], title = "Translation Data-Loss Audit (pacs.008 ↔ MT103)"): string {
  const v = (p: PairResult) => verdict(p.findings);
  const count = (k: string) => pairs.filter((p) => v(p) === k).length;
  const byRule: Record<string, number> = {};
  for (const p of pairs) for (const f of p.findings) byRule[f.rule] = (byRule[f.rule] ?? 0) + 1;
  const out = [`# ${title}`, "", `**${pairs.length} payment(s):** ${count("CRITICAL")} critical · ${count("DATA LOST")} lost data · ${count("MINOR")} minor · ${count("CLEAN")} clean.`, ""];
  if (Object.keys(byRule).length > 0 && pairs.length > 1) out.push(mdTable(["Issue", "Payments"], Object.entries(byRule).sort((a, b) => b[1] - a[1])), "");
  for (const p of pairs) {
    out.push(`## ${ICON[v(p)]} ${p.name}: ${v(p)}`, "", p.uetr ? `UETR ${p.uetr}` : "", "");
    if (p.findings.length) out.push(mdTable(["Severity", "Field", "ISO 20022 (MX)", "MT103", "What it means"], p.findings.map((f) => [f.severity.toUpperCase(), f.field, f.mx, f.mt, f.message])), "");
    else out.push("Everything checked made it across intact.", "");
  }
  out.push("_Generated by Hyniqe Hub · Translation Data-Loss Auditor. Runs locally. Checks the fields most often lost between ISO 20022 and MT; it is not a full message validation._");
  return out.join("\n") + "\n";
}

export function toResultCsv(pairs: PairResult[]): string {
  return toCsv(pairs.flatMap((p) => p.findings.map((f) => ({ payment: p.name, uetr: p.uetr, severity: f.severity, rule: f.rule, field: f.field, mx: f.mx, mt: f.mt, message: f.message }))), ["payment", "uetr", "severity", "rule", "field", "mx", "mt", "message"]);
}
