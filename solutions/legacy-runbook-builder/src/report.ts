import { mdTable, toCsv } from "../../shared/table.ts";
import type { GapType, Runbook } from "./extract.ts";

const GAP_TITLE: Record<GapType, string> = {
  HARDCODED_SECRET: "Password or key written in the document/script",
  KEY_PERSON: "Depends on one named person",
  DESTRUCTIVE_COMMAND: "Deletes or overwrites data",
  NO_FAILURE_PATH: "No failure / escalation steps",
  VAGUE_CHECK: "Check with no clear pass/fail rule",
  MANUAL_SPREADSHEET: "Manual spreadsheet / macro step",
  HARDCODED_ENV: "Hard-coded server, IP or share",
  NO_OWNER: "No owner named",
  NO_SCHEDULE: "No schedule or cut-off",
  TODO_WORKAROUND: "Workaround or TODO nobody explained",
  LEGACY_TECH: "End-of-life technology",
  UNEXPLAINED_ACRONYM: "Acronym with no explanation",
};
const ORDER: GapType[] = ["HARDCODED_SECRET", "KEY_PERSON", "DESTRUCTIVE_COMMAND", "NO_FAILURE_PATH", "VAGUE_CHECK", "MANUAL_SPREADSHEET", "HARDCODED_ENV", "NO_OWNER", "NO_SCHEDULE", "TODO_WORKAROUND", "LEGACY_TECH", "UNEXPLAINED_ACRONYM"];

export function toMarkdown(rb: Runbook): string {
  const out: string[] = [];
  out.push(`# Runbook: ${rb.title}`, "");
  out.push(`_Draft generated from ${rb.sources.map((s) => `${s.name} (${s.kind})`).join(", ")}. Review every step with the current process owner before relying on it._`, "");
  out.push(`**Documentation completeness: ${Math.round(rb.completeness.score * 100)}%**  `, rb.completeness.checks.map((c) => `${c.ok ? "✅" : "❌"} ${c.label}`).join(" · "), "");
  if (rb.purpose) out.push("## Purpose", "", rb.purpose, "");
  if (rb.schedule.length) out.push("## When it runs and cut-offs", "", ...rb.schedule.map((s) => `- ${s.text} _(${s.source}:${s.line})_`), "");
  if (rb.steps.length) {
    out.push("## Steps", "");
    for (const s of rb.steps) {
      const tag = s.kind === "check" ? " ✔︎ **check**" : s.kind === "decision" ? " ⑂ **decision**" : "";
      out.push(`${s.n}. ${s.text}${tag}${s.command ? `  \n   \`${s.command.slice(0, 140)}\`` : ""}  \n   _source: ${s.source}:${s.line}_`);
    }
    out.push("");
  }
  if (rb.systems.length || rb.hosts.length || rb.files.length) {
    out.push("## Systems, servers and files", "");
    if (rb.systems.length) out.push(`**Systems:** ${rb.systems.join(", ")}`, "");
    if (rb.hosts.length) out.push(`**Servers / shares:** ${rb.hosts.join(", ")}`, "");
    if (rb.files.length) out.push(`**Files / datasets:** ${rb.files.map((f) => "`" + f + "`").join(", ")}`, "");
  }
  if (rb.contacts.length) out.push("## People this process depends on", "", ...rb.contacts.map((c) => `- **${c.who}**: "${c.context}"`), "");
  const gapsByType = ORDER.map((t) => [t, rb.gaps.filter((g) => g.type === t)] as const).filter(([, l]) => l.length);
  if (gapsByType.length) {
    out.push(`## Knowledge gaps to close (${rb.gaps.length})`, "", "These are the things that would break if the person who knows this process left.", "");
    for (const [t, list] of gapsByType) {
      out.push(`### ${GAP_TITLE[t]} (${list.length})`, "", `_Fix: ${list[0].advice}_`, "");
      for (const g of list.slice(0, 12)) out.push(`- ${g.line ? `${g.source}:${g.line}: ` : ""}${g.text.length > 160 ? g.text.slice(0, 160) + "…" : g.text}`);
      if (list.length > 12) out.push(`- …and ${list.length - 12} more`);
      out.push("");
    }
  }
  if (rb.glossary.length) out.push("## Glossary", "", mdTable(["Term", "Meaning"], rb.glossary.map((g) => [g.term, g.meaning || "❓ unknown: ask the team"])), "");
  out.push("## Questions for the process owner", "", ...ownerQuestions(rb).map((q) => `- [ ] ${q}`), "");
  out.push("_Generated by Hyniqe Hub · Legacy Runbook Builder. Runs locally. Extraction is rule-based. Use the AI prompt (`--prompt`) to have Claude turn this draft into polished prose._");
  return out.join("\n") + "\n";
}

export function ownerQuestions(rb: Runbook): string[] {
  const q: string[] = [];
  const has = (t: GapType) => rb.gaps.some((g) => g.type === t);
  if (has("NO_OWNER")) q.push("Who owns this process, and who is the backup?");
  if (has("NO_SCHEDULE")) q.push("When does this run, and what are the hard cut-offs?");
  if (has("NO_FAILURE_PATH")) q.push("What happens if a file is late, a job fails or a system is down? Who do we call, and what's the business impact?");
  for (const g of rb.gaps.filter((x) => x.type === "VAGUE_CHECK").slice(0, 5)) q.push(`"${g.text.slice(0, 100)}": what exactly counts as OK? Which fields, values or tolerances?`);
  for (const c of rb.contacts.slice(0, 5)) q.push(`What does ${c.who} know or do here that isn't written down? Who else can do it?`);
  if (has("MANUAL_SPREADSHEET")) q.push("Where does the spreadsheet/macro live, what does it calculate, and who can maintain it?");
  if (has("HARDCODED_SECRET")) q.push("Which credentials are embedded? Can they move to a vault and be rotated?");
  for (const g of rb.glossary.filter((x) => !x.known).slice(0, 5)) q.push(`What does "${g.term}" mean here?`);
  return q;
}

/** A ready-to-paste prompt so an AI assistant can turn the extracted structure into a polished runbook. */
export function aiPrompt(rb: Runbook, originals: { name: string; text: string }[]): string {
  const masked = originals.map((o) => `--- ${o.name} ---\n${o.text.replace(/((?:password|passwd|pwd|pass|secret|token|api[_-]?key)\s*[:=]\s*)\S+/gi, "$1****").replace(/(sshpass\s+-p\s+)\S+/g, "$1****")}`).join("\n\n");
  return [
    "You are an operations documentation specialist at a bank. Turn the material below into a clear runbook a new team member could follow on their first day.",
    "",
    "Rules:",
    "- Use only facts in the material. Where something is missing or vague, write [ASK OWNER: question] instead of guessing.",
    "- Sections: Purpose · When it runs & cut-offs · Prerequisites & access · Step-by-step (numbered, one action per step, with the system used and what 'done' looks like) · Checks & controls (exact pass/fail rules) · If something goes wrong (by failure type) · Contacts & escalation · Glossary · Open questions.",
    "- Never include passwords or keys; note that a credential exists and must move to a vault.",
    "- Plain English. Explain every acronym the first time.",
    "",
    "Pre-extracted structure (from an automated scan; may be incomplete):",
    "```json",
    JSON.stringify({ title: rb.title, schedule: rb.schedule.map((s) => s.text), steps: rb.steps.map((s) => s.text), systems: rb.systems, hosts: rb.hosts, files: rb.files, contacts: rb.contacts.map((c) => c.who), gaps: rb.gaps.map((g) => `${g.type}: ${g.text.slice(0, 120)}`), glossary: rb.glossary }, null, 2),
    "```",
    "",
    "Original material (secrets masked):",
    masked,
  ].join("\n");
}

export function gapsCsv(rb: Runbook): string {
  return toCsv(rb.gaps.map((g) => ({ type: g.type, title: GAP_TITLE[g.type], source: g.source, line: g.line || "", text: g.text, advice: g.advice })), ["type", "title", "source", "line", "text", "advice"]);
}
