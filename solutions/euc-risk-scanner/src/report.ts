import { mdTable, toCsv } from "../../shared/table.ts";
import type { FileReport } from "./scan.ts";

const ICON = { HIGH: "🔴", MEDIUM: "🟠", LOW: "🟢" } as const;

export function toMarkdown(list: FileReport[], title = "Spreadsheet (EUC) risk register"): string {
  const c = (t: string) => list.filter((f) => f.tier === t).length;
  const out = [
    `# ${title}`, "",
    `**${list.length} file(s):** ${c("HIGH")} high · ${c("MEDIUM")} medium · ${c("LOW")} low risk. ${list.filter((f) => f.macros).length} with macros, ${list.filter((f) => f.externalLinks.length).length} linked to other files, ${list.filter((f) => f.connections.some((x) => x.hasPassword)).length} with a stored password.`, "",
    mdTable(["Risk", "File", "Formulas", "Macros", "Links", "Hidden sheets", "Last changed by", "Modified"], [...list].sort((a, b) => b.score - a.score).map((f) => [`${ICON[f.tier]} ${f.tier} (${f.score})`, f.file, f.formulas, f.macros ? "yes" : "-", f.externalLinks.length || "-", f.sheets.filter((s) => s.state !== "visible").length || "-", f.lastModifiedBy || "-", f.modified || "-"])), "",
  ];
  for (const f of [...list].sort((a, b) => b.score - a.score)) {
    if (!f.findings.length) continue;
    out.push(`## ${ICON[f.tier]} ${f.file}`, "", ...f.findings.map((x) => `- ${x.message}`), "");
    if (f.examples.length) out.push(mdTable(["Sheet", "Cell", "Formula", "Why"], f.examples.slice(0, 8).map((e) => [e.sheet, e.cell, e.formula.slice(0, 80), e.why])), "");
  }
  out.push("## What to do with HIGH-risk files", "",
    "1. Name an owner and record what decision or report the spreadsheet feeds.",
    "2. Move typed-in rates and thresholds to a clearly labelled input sheet, and remove stored passwords.",
    "3. Put it under version control and have someone else review the formulas and macros.",
    "4. If it's business-critical, plan to replace it with a controlled system.", "",
    "_Generated by Hyniqe Hub · Spreadsheet (EUC) Risk Scanner. Runs locally; files are read, never changed or uploaded._");
  return out.join("\n") + "\n";
}

export function registerCsv(list: FileReport[]): string {
  return toCsv(list.map((f) => ({ file: f.file, format: f.format, risk: f.tier, score: f.score, author: f.author, last_modified_by: f.lastModifiedBy, modified: f.modified, sheets: f.sheets.length, hidden_sheets: f.sheets.filter((s) => s.state !== "visible").map((s) => `${s.name} (${s.state})`).join("; "), formulas: f.formulas, macros: f.macros ? "yes" : "no", external_links: f.externalLinks.join("; "), connections: f.connections.map((c) => `${c.name} (${c.type}${c.hasPassword ? ", password stored" : ""})`).join("; "), findings: f.findings.map((x) => x.message).join(" | "), owner: "", purpose: "", criticality: "" })),
    ["file", "format", "risk", "score", "author", "last_modified_by", "modified", "sheets", "hidden_sheets", "formulas", "macros", "external_links", "connections", "findings", "owner", "purpose", "criticality"]);
}
