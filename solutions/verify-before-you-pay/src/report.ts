import { mdTable, toCsv } from "../../shared/table.ts";
import type { Assessment } from "./assess.ts";

const ICON = { CRITICAL: "🔴", HIGH: "🟠", MEDIUM: "🟡", LOW: "🟢" } as const;

export function oneToMarkdown(a: Assessment): string {
  const r = a.request;
  const out: string[] = [];
  out.push(`## ${ICON[a.level]} ${a.level} risk (${a.score}/100): ${r.id}`, "");
  const head = [r.requested_by && `From: ${r.requested_by}${r.requester_title ? " (" + r.requester_title + ")" : ""}`, r.channel && `via ${r.channel}`, r.amount !== null && `${r.amount.toLocaleString("en-US")} ${r.currency}`, r.payee && `to ${r.payee}`].filter(Boolean).join(" · ");
  if (head) out.push(head, "");
  out.push(`**What to do:** ${a.advice}`, "");
  if (a.flags.length) {
    out.push("**Warning signs**", "", ...a.flags.map((f) => `- ${f.label}: ${f.detail}`), "");
  }
  const req = a.controls.filter((c) => c.required);
  if (req.length) {
    out.push("**Required checks**", "", mdTable(["Check", "Status", "Why"], req.map((c) => [c.id.replace(/_/g, " ").toLowerCase(), c.status === "not logged" ? "TO DO" : c.status.toUpperCase(), c.why + (c.detail ? " " + c.detail : "")])), "");
  }
  if (a.level !== "LOW") {
    out.push("**Callback script**", "", ...a.callback_script.map((l, i) => `${i + 1}. ${l}`), "");
    out.push("**Challenge questions**", "", ...a.challenge_questions.map((q) => `- ${q}`), "");
  }
  return out.join("\n");
}

export function toMarkdown(list: Assessment[], title = "Verify-Before-You-Pay report"): string {
  const count = (l: string) => list.filter((a) => a.level === l).length;
  const breaches = list.filter((a) => a.breaches.length);
  const paidRisky = list.filter((a) => (a.level === "HIGH" || a.level === "CRITICAL") && a.request.paid_at && a.breaches.length);
  const out = [
    `# ${title}`, "",
    `**${list.length} payment requests:** ${count("CRITICAL")} critical · ${count("HIGH")} high · ${count("MEDIUM")} medium · ${count("LOW")} low.`,
    `${breaches.length} request(s) skipped a required verification step; **${paidRisky.length} high/critical request(s) were paid without completing the required checks**${paidRisky.length ? " (" + paidRisky.map((a) => a.request.id).join(", ") + "). Contact your bank about a recall now" : ""}.`, "",
  ];
  if (list.length > 1) {
    out.push(mdTable(["Request", "Level", "Score", "From", "Amount", "Skipped checks"],
      [...list].sort((a, b) => b.score - a.score).map((a) => [a.request.id, a.level, a.score, a.request.requested_by, a.request.amount !== null ? `${a.request.amount.toLocaleString("en-US")} ${a.request.currency}` : "", a.breaches.map((b) => b.id).join(", ") || "-"])), "");
  }
  for (const a of [...list].sort((x, y) => y.score - x.score)) if (a.level !== "LOW" || a.breaches.length) out.push(oneToMarkdown(a), "");
  out.push("_Generated by Hyniqe Hub · Verify-Before-You-Pay. Runs locally. A risk score supports judgement; it does not prove a request is real or fake._");
  return out.join("\n") + "\n";
}

export function toResultCsv(list: Assessment[]): string {
  return toCsv(list.map((a) => ({
    request_id: a.request.id, level: a.level, score: a.score, requested_by: a.request.requested_by, channel: a.request.channel,
    amount: a.request.amount ?? "", currency: a.request.currency, payee: a.request.payee,
    flags: a.flags.map((f) => f.id).join(";"), skipped_checks: a.breaches.map((b) => b.id).join(";"), advice: a.advice,
  })), ["request_id", "level", "score", "requested_by", "channel", "amount", "currency", "payee", "flags", "skipped_checks", "advice"]);
}
