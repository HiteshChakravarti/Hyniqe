import { mdTable, toCsv } from "../../shared/table.ts";
import { type Assessed, RULES } from "./predict.ts";

export function toMarkdown(list: Assessed[], title = "T+1 Settlement Fail Predictor"): string {
  const n = (r: string) => list.filter((a) => a.risk === r).length;
  const byRule: Record<string, number> = {};
  const byCp: Record<string, number> = {};
  for (const a of list) for (const i of a.issues) { byRule[i.rule] = (byRule[i.rule] ?? 0) + 1; if (i.severity === "high") byCp[a.trade.counterparty || "(blank)"] = (byCp[a.trade.counterparty || "(blank)"] ?? 0) + 1; }
  const out = [
    `# ${title}`, "",
    `**${list.length} trades:** ${n("HIGH")} likely to fail under T+1 · ${n("MEDIUM")} at risk · ${n("LOW")} look ready.`,
    `${list.filter((a) => a.t1_applies).length} trade(s) assessed against the T+1 cycle.`, "",
  ];
  const rank = { high: 0, medium: 1, low: 2 } as Record<string, number>;
  const rows = Object.entries(byRule).sort((a, b) => rank[RULES[a[0]].severity] - rank[RULES[b[0]].severity] || b[1] - a[1]).map(([r, c]) => [RULES[r].severity.toUpperCase(), RULES[r].title, c, RULES[r].fix]);
  if (rows.length) out.push("## Why trades would fail", "", mdTable(["Severity", "Issue", "Trades", "Fix"], rows), "");
  const cps = Object.entries(byCp).sort((a, b) => b[1] - a[1]).slice(0, 10);
  if (cps.length) out.push("## Counterparties to fix first", "", mdTable(["Counterparty", "High-severity issues"], cps), "");
  const flagged = list.filter((a) => a.risk !== "LOW");
  if (flagged.length) out.push("## Trades at risk", "", mdTable(["Risk", "Trade", "Counterparty", "Trade date", "Settles", "Issues"], flagged.sort((a, b) => (a.risk === b.risk ? 0 : a.risk === "HIGH" ? -1 : 1)).map((a) => [a.risk, a.trade.id || `line ${a.trade.line}`, a.trade.counterparty, a.trade.trade_date, a.trade.settlement_date, a.issues.map((i) => i.message).join(" ")])), "");
  out.push(
    "## The T+1 day in one line", "",
    "Trade → allocate → confirm/affirm → instruct, **all on trade date**, with SSIs and FX already in place. Anything that needs a second day becomes a settlement fail (and a penalty) under T+1.", "",
    "_Generated by Hyniqe Hub · T+1 Settlement Fail Predictor. Runs locally. Times in your file are read as market local time. Check your CSDs' and custodians' own cut-offs._",
  );
  return out.join("\n") + "\n";
}

export function toResultCsv(list: Assessed[]): string {
  return toCsv(list.map((a) => ({ line: a.trade.line, trade_id: a.trade.id, counterparty: a.trade.counterparty, trade_date: a.trade.trade_date, settlement_date: a.trade.settlement_date, expected_t1: a.expected_settlement, risk: a.risk, rules: a.issues.map((i) => i.rule).join(";"), details: a.issues.map((i) => i.message).join(" ") })),
    ["line", "trade_id", "counterparty", "trade_date", "settlement_date", "expected_t1", "risk", "rules", "details"]);
}
