import { mdTable, toCsv } from "../../shared/table.ts";
import { type Arrangement, type Issue, RULE_TITLES } from "./precheck.ts";

export function toMarkdown(list: Arrangement[], issues: Issue[], title = "DORA Register of Information: pre-check"): string {
  const errors = issues.filter((i) => i.severity === "error");
  const clean = list.filter((a) => !errors.some((e) => e.line === a.line)).length;
  const byRule: Record<string, Issue[]> = {};
  for (const i of issues) (byRule[i.rule] ??= []).push(i);
  const crit = list.filter((a) => a.critical).length;
  const out = [
    `# ${title}`, "",
    `**${list.length} arrangements** (${crit} supporting critical or important functions): **${clean} ready**, ${list.length - clean} with errors. ${errors.length} errors and ${issues.length - errors.length} warnings in total.`, "",
  ];
  if (Object.keys(byRule).length) {
    out.push("## Summary", "", mdTable(["Issue", "Severity", "Count"], Object.entries(byRule).sort((a, b) => b[1].length - a[1].length).map(([r, l]) => [RULE_TITLES[r] ?? r, l.some((x) => x.severity === "error") ? "error" : "warning", l.length])), "");
    out.push("## Fix list", "", mdTable(["Line", "Arrangement", "Field", "Value", "Issue"], issues.sort((a, b) => a.line - b.line || (a.severity === "error" ? -1 : 1)).map((i) => [i.line, i.ref, i.field, i.value, i.message])), "");
  } else out.push("No issues found by these checks.", "");
  out.push(
    "## Before you submit", "",
    "1. Fix the errors here, then convert to the official xBRL-CSV templates.",
    "2. Run your authority's / the ESAs' validation rules on the converted files: this pre-check does not replace them.",
    "3. Keep the register current during the year; it's also what supervisors use to map concentration risk.", "",
    "_Generated by Hyniqe Hub · DORA Register Pre-Check. Runs locally. Not legal or regulatory advice._",
  );
  return out.join("\n") + "\n";
}

export function toIssuesCsv(issues: Issue[]): string {
  return toCsv(issues as unknown as Record<string, unknown>[], ["line", "ref", "field", "value", "rule", "severity", "message"]);
}
