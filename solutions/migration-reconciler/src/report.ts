import { mdTable, toCsv } from "../../shared/table.ts";
import { type DiffKind, type Result, SERIOUS } from "./reconcile.ts";

const LABEL: Record<DiffKind, string> = { TRUNCATED: "truncated", EMPTIED: "emptied (value lost)", POPULATED: "filled in (was empty)", CHANGED: "changed", NUMBER_CHANGED: "number changed", DATE_CHANGED: "date changed", CASE_SPACING: "case/spacing only", FORMAT_ONLY: "format only" };

export function toMarkdown(r: Result, title = "Migration reconciliation"): string {
  const pass = !r.missing.length && !r.extra.length && !r.dupSource.length && !r.dupTarget.length && !r.diffs.some((d) => SERIOUS.includes(d.kind)) && r.fields.every((f) => f.sourceSum === undefined || f.sourceSum === f.targetSum);
  const out = [
    `# ${title}`, "",
    `## ${pass ? "✅ RECONCILED" : "❌ NOT RECONCILED"}`, "",
    mdTable(["Check", "Source", "Target", "Result"], [
      ["Records", r.sourceRows, r.targetRows, r.sourceRows === r.targetRows ? "✅" : "❌"],
      ["Matched by key", r.matched, r.matched, ""],
      ["Missing in target", r.missing.length, "", r.missing.length ? "❌" : "✅"],
      ["Extra in target", "", r.extra.length, r.extra.length ? "❌" : "✅"],
      ["Duplicate keys", r.dupSource.length, r.dupTarget.length, r.dupSource.length || r.dupTarget.length ? "❌" : "✅"],
      ["Records with real differences", "", r.recordsWithSeriousDiffs, r.recordsWithSeriousDiffs ? "❌" : "✅"],
    ]), "",
  ];
  const totals = r.fields.filter((f) => f.sourceSum !== undefined);
  if (totals.length) out.push("## Control totals", "", mdTable(["Field", "Source total", "Target total", "Difference"], totals.map((f) => [f.field, f.sourceSum!.toLocaleString("en-US"), f.targetSum!.toLocaleString("en-US"), f.sourceSum === f.targetSum ? "✅ 0" : `❌ ${(Math.round((f.targetSum! - f.sourceSum!) * 100) / 100).toLocaleString("en-US")}`])), "");
  out.push("## Field by field", "", mdTable(["Source field", "Target field", "Match %", "Real differences", "Harmless differences"], r.fields.map((f) => {
    const serious = SERIOUS.filter((k) => f.kinds[k]).map((k) => `${f.kinds[k]} ${LABEL[k]}`).join(", ");
    const harmless = (["FORMAT_ONLY", "CASE_SPACING", "POPULATED"] as DiffKind[]).filter((k) => f.kinds[k]).map((k) => `${f.kinds[k]} ${LABEL[k]}`).join(", ");
    return [f.field, f.target, f.compared ? `${((f.same / f.compared) * 100).toFixed(2)}%` : "-", serious || "-", harmless || "-"];
  })), "");
  if (r.unmappedSource.length || r.unmappedTarget.length) out.push(`**Not compared:** source-only columns: ${r.unmappedSource.join(", ") || "none"}; target-only columns: ${r.unmappedTarget.join(", ") || "none"}. Use \`--map\` if they correspond.`, "");
  const sample = r.diffs.filter((d) => SERIOUS.includes(d.kind)).slice(0, 25);
  if (sample.length) out.push("## Examples of real differences", "", mdTable(["Key", "Field", "Source", "Target", "Type"], sample.map((d) => [d.key, d.field, d.source, d.target, LABEL[d.kind]])), "");
  if (r.missing.length) out.push(`**Missing in target (first 20):** ${r.missing.slice(0, 20).join(", ")}`, "");
  if (r.extra.length) out.push(`**Extra in target (first 20):** ${r.extra.slice(0, 20).join(", ")}`, "");
  out.push("## Sign-off", "", "| Role | Name | Date | Signature |", "| --- | --- | --- | --- |", "| Data owner | | | |", "| Migration lead | | | |", "| Independent reviewer | | | |", "",
    "_Generated by Hyniqe Hub · Migration Reconciler. Runs locally. Keep this report with the extracts it was run on (record file names, row counts and extraction times)._");
  return out.join("\n") + "\n";
}

export function diffsCsv(r: Result): string {
  const rows = [...r.missing.map((k) => ({ key: k, field: "(record)", source: "present", target: "missing", kind: "MISSING" })), ...r.extra.map((k) => ({ key: k, field: "(record)", source: "missing", target: "present", kind: "EXTRA" })), ...r.diffs];
  return toCsv(rows as Record<string, unknown>[], ["key", "field", "source", "target", "kind"]);
}
