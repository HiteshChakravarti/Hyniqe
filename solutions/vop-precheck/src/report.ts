import { mdTable, toCsv } from "../../shared/table.ts";
import type { Outcome, Result } from "./precheck.ts";

const ORDER: Outcome[] = ["WILL BE REJECTED", "LIKELY NO MATCH", "LIKELY CLOSE MATCH", "UNKNOWN", "NOT IN VOP SCOPE", "MATCH"];
const ICON: Record<Outcome, string> = { "WILL BE REJECTED": "⛔", "LIKELY NO MATCH": "🔴", "LIKELY CLOSE MATCH": "🟠", UNKNOWN: "⚪", "NOT IN VOP SCOPE": "➖", MATCH: "🟢" };

export function toMarkdown(list: Result[], title = "Verification of Payee pre-check"): string {
  const count = (o: Outcome) => list.filter((r) => r.outcome === o).length;
  const value = (o: Outcome) => list.filter((r) => r.outcome === o).reduce((s, r) => s + (r.payment.amount ?? 0), 0);
  const fix = list.filter((r) => ["WILL BE REJECTED", "LIKELY NO MATCH", "LIKELY CLOSE MATCH"].includes(r.outcome));
  const out = [
    `# ${title}`, "",
    `**${list.length} payments.** ${fix.length} need attention before you send the file (value ${fix.reduce((s, r) => s + (r.payment.amount ?? 0), 0).toLocaleString("en-US")}).`, "",
    mdTable(["Predicted result", "Payments", "Value"], ORDER.filter((o) => count(o)).map((o) => [`${ICON[o]} ${o}`, count(o), value(o).toLocaleString("en-US")])), "",
  ];
  if (fix.length) {
    out.push("## Fix before sending", "", mdTable(["Line", "Payee name in file", "IBAN", "Prediction", "Why", "Do this"],
      fix.sort((a, b) => ORDER.indexOf(a.outcome) - ORDER.indexOf(b.outcome)).map((r) => [r.payment.line, r.payment.name, r.payment.iban, `${ICON[r.outcome]} ${r.outcome}`, r.reason, r.suggestion])), "");
  }
  const warn = list.filter((r) => r.warnings.length);
  if (warn.length) out.push("## Data warnings", "", ...warn.map((r) => `- Line ${r.payment.line} (${r.payment.name || "no name"}): ${r.warnings.join(" ")}`), "");
  const unknown = list.filter((r) => r.outcome === "UNKNOWN");
  if (unknown.length) out.push(`## ${unknown.length} payee(s) not in your supplier master`, "", "Ask these suppliers for the exact account-holder name on their bank account, and store it. That single step prevents most mismatches.", "");
  out.push(
    "## What the results mean", "",
    "- **Match:** the payment goes ahead as normal.",
    "- **Close match:** your bank shows the payer the name the payee's bank holds; someone has to confirm or correct it.",
    "- **No match:** your bank warns that the name doesn't fit the account. If you pay anyway, you carry the risk if the money goes to the wrong person.", "",
    "_Generated by Hyniqe Hub · VoP Pre-Checker. Runs locally. Each bank uses its own matching rules, so these are predictions, not the bank's answer._",
  );
  return out.join("\n") + "\n";
}

export function toResultCsv(list: Result[]): string {
  return toCsv(list.map((r) => ({ line: r.payment.line, payee_name: r.payment.name, iban: r.payment.iban, amount: r.payment.amount ?? "", prediction: r.outcome, reason: r.reason, suggestion: r.suggestion, name_on_file: r.master?.legal_name ?? "", warnings: r.warnings.join(" ") })),
    ["line", "payee_name", "iban", "amount", "prediction", "reason", "suggestion", "name_on_file", "warnings"]);
}
