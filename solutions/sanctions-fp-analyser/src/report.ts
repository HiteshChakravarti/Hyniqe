import { mdTable, toCsv } from "../../shared/table.ts";
import type { Analysis } from "./analyse.ts";

const h = (m: number) => Math.round(m / 60).toLocaleString("en-US");

export function toMarkdown(a: Analysis, title = "Sanctions false-positive analysis"): string {
  const out = [
    `# ${title}`, "",
    `**${a.total.toLocaleString("en-US")} alerts:** ${a.fps.toLocaleString("en-US")} false positives · ${a.trues} true matches · ${a.escalated} escalated · ${a.open} open.`,
    `False-positive rate (closed alerts): **${(a.fpRate * 100).toFixed(1)}%** · analyst time on false positives: **~${h(a.fpMinutes)} hours**${a.minutesAssumed ? " (30 minutes assumed where time wasn't recorded)" : ""}.`, "",
  ];
  if (a.drivers.length) {
    out.push("## What's driving the false positives", "", mdTable(["Driver", "False positives", "True matches in group", "Hours", "Safe to tune?"],
      a.drivers.map((d) => [d.title, d.fps, d.trues, h(d.minutes), d.safe ? "Candidate (test first)" : "⚠️ No: contains true matches"])), "");
    for (const d of a.drivers) out.push(`### ${d.title}`, "", d.detail, "", `**What to test:** ${d.action}`, "");
  } else out.push("No dominant false-positive driver found in this sample.", "");
  if (a.goodGuys.length) {
    out.push("## Good-guy candidates (top 15)", "", mdTable(["Screened party", "List entry", "List", "Times cleared", "Hours", "First → last"],
      a.goodGuys.slice(0, 15).map((g) => [g.screened, g.matched, g.list, g.clears, h(g.minutes), `${g.first} → ${g.last}`])), "");
  }
  out.push("## Breakdown", "", "**By field**", "", mdTable(["Field", "FP", "True"], a.byField), "", "**By list**", "", mdTable(["List", "FP", "True"], a.byList.slice(0, 10)), "");
  if (a.byBand.length) out.push("**By match score**", "", mdTable(["Score band", "FP", "True"], a.byBand), "");
  if (a.byMsg.some(([k]) => k !== "(blank)")) out.push("**By message type**", "", mdTable(["Message type", "FP", "True"], a.byMsg.slice(0, 10)), "");
  out.push(
    "## Before changing anything", "",
    "1. Test every proposed change against your known true matches and a test file of sanctioned names (below-the-line testing).",
    "2. Get Compliance sign-off and document the rationale. Regulators examine how false positives are managed.",
    "3. Re-review good-guy rules whenever the sanctions lists change.", "",
    "_Generated by Hyniqe Hub · Sanctions False-Positive Analyser. Runs locally. It analyses past decisions; it never clears alerts and is not compliance advice._",
  );
  return out.join("\n") + "\n";
}

export function goodGuysCsv(a: Analysis): string {
  return toCsv(a.goodGuys as unknown as Record<string, unknown>[], ["screened", "matched", "list", "clears", "trues", "minutes", "first", "last"]);
}
