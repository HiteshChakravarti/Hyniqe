import { mdTable, toCsv } from "../../shared/table.ts";
import type { Finding, Summary, Category } from "./scan.ts";

const LABEL: Record<Category, string> = {
  SECRET_EXPOSED: "🔑 Private key in files",
  BROKEN_NOW: "🔴 Broken today",
  QUANTUM_VULNERABLE: "🟠 Quantum-vulnerable",
  REVIEW: "🟡 Review",
  QUANTUM_SAFE: "🟢 Quantum-safe",
  PQC_READY: "✅ Post-quantum ready",
};

export function toMarkdown(findings: Finding[], s: Summary, title = "Post-Quantum Crypto Inventory"): string {
  const active = findings.filter((f) => !f.in_comment);
  const out = [
    `# ${title}`, "",
    `Scanned **${s.files_scanned} files** and found **${s.active_findings} uses of cryptography** (${s.findings - s.active_findings} more in comments, listed at the end).`,
    `**${s.by_category.BROKEN_NOW}** are weak today, **${s.by_category.QUANTUM_VULNERABLE}** will break once large quantum computers arrive, and ${s.files_with_quantum_vulnerable} file(s) need migration work.`,
    `Post-quantum readiness of public-key crypto: **${Math.round(s.pqc_readiness * 100)}%**.`, "",
    mdTable(["Status", "Count", "Meaning"], (Object.keys(LABEL) as Category[]).map((c) => [LABEL[c], s.by_category[c], MEANING[c]])), "",
  ];
  const order: Category[] = ["SECRET_EXPOSED", "BROKEN_NOW", "QUANTUM_VULNERABLE", "REVIEW"];
  for (const c of order) {
    const list = active.filter((f) => f.category === c);
    if (!list.length) continue;
    out.push(`## ${LABEL[c]} (${list.length})`, "");
    out.push(mdTable(["Where", "What", "Why", "Move to"], list.map((f) => [`${f.file}:${f.line}`, `${f.family}${f.param ? " (" + f.param + ")" : ""}`, f.why, f.fix])), "");
  }
  const good = active.filter((f) => f.category === "PQC_READY");
  if (good.length) out.push(`## ${LABEL.PQC_READY}`, "", ...good.map((f) => `- ${f.file}:${f.line}: ${f.family}${f.param ? " (" + f.param + ")" : ""}`), "");
  const comments = findings.filter((f) => f.in_comment);
  if (comments.length) out.push("## Mentions in comments (not counted)", "", ...comments.map((f) => `- ${f.file}:${f.line}: ${f.family}: \`${f.snippet}\``), "");
  out.push(
    "## Suggested order of work", "",
    "1. **Remove and rotate exposed private keys.**",
    "2. **Fix what is broken today**: MD5/SHA-1, DES/3DES/RC4, ECB mode, RSA under 2048 bits, TLS 1.0/1.1.",
    "3. **Protect long-lived secrets first** from \"record now, decrypt later\": move key exchange and encryption (TLS, VPN, file encryption, key wrapping) to hybrid X25519MLKEM768 / ML-KEM.",
    "4. **Plan signatures** (code signing, certificates, payment message signing, JWT) for ML-DSA / SLH-DSA as your vendors, HSMs and partners support them.",
    "5. Ask vendors and counterparties (SWIFT, card schemes, HSM and cloud providers) for their post-quantum roadmaps; much of your crypto lives in their products, not your code.", "",
    "_Generated by Hyniqe Hub · PQC Crypto Inventory. Runs locally. A pattern scan finds most crypto in code and config, but not crypto hidden inside binaries, libraries, HSMs or third-party services._",
  );
  return out.join("\n") + "\n";
}

const MEANING: Record<Category, string> = {
  SECRET_EXPOSED: "Private key stored in the code base: remove and rotate",
  BROKEN_NOW: "Weak against today's attackers: fix first",
  QUANTUM_VULNERABLE: "Fine today, broken by a large quantum computer: plan migration",
  REVIEW: "Probably fine; confirm key size or mode",
  QUANTUM_SAFE: "Symmetric crypto with enough margin: no action",
  PQC_READY: "Already uses NIST post-quantum or hybrid algorithms",
};

export function toResultCsv(findings: Finding[]): string {
  return toCsv(findings as unknown as Record<string, unknown>[], ["file", "line", "category", "family", "param", "primitive", "priority", "in_comment", "rule", "snippet", "why", "fix"]);
}
