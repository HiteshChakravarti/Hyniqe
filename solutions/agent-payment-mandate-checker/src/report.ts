import { mdTable, toCsv } from "../../shared/table.ts";
import { type CheckResult, RULES } from "./checker.ts";

export function toMarkdown(r: CheckResult, title = "Agent Payment Mandate Check"): string {
  const s = r.summary;
  const pct = (x: number) => `${Math.round(x * 100)}%`;
  const lines: string[] = [];
  lines.push(`# ${title}`, "");
  lines.push(
    `**${s.total} payments** by ${s.agents.length} agent(s): **${s.block} BLOCK**, **${s.review} REVIEW**, ${s.ok} OK.`,
    `Value needing attention: **${s.value_at_risk_base.toLocaleString("en-US")}** of ${s.total_value_base.toLocaleString("en-US")} (mandate base currency).`,
    `Audit-trail completeness: **${pct(s.audit_trail_completeness)}** of payments carry id, time, agent, payee, amount, currency, purpose, mandate reference and (where required) a timed human approval.`,
    "",
  );
  const ruleRows = Object.entries(s.by_rule)
    .sort((a, b) => sevRank(RULES[a[0]].severity) - sevRank(RULES[b[0]].severity) || b[1] - a[1])
    .map(([rule, n]) => [RULES[rule].severity.toUpperCase(), RULES[rule].title, n]);
  if (ruleRows.length) {
    lines.push("## What we found", "", mdTable(["Severity", "Issue", "Payments"], ruleRows), "");
  }
  const flagged = r.payments.filter((p) => p.verdict !== "OK");
  if (flagged.length) {
    lines.push("## Payments to act on", "");
    lines.push(
      mdTable(
        ["Verdict", "Payment", "When", "Agent", "Payee", "Amount", "Why"],
        flagged
          .sort((a, b) => (a.verdict === b.verdict ? 0 : a.verdict === "BLOCK" ? -1 : 1))
          .map((p) => [
            p.verdict,
            p.payment_id || `line ${p.line}`,
            p.timestamp_raw,
            p.agent_id,
            p.payee,
            `${p.amount ?? "?"} ${p.currency}`,
            p.findings.filter((x) => x.severity !== "low").map((x) => x.message).join(" "),
          ]),
      ),
      "",
    );
  }
  if (s.mandates_unused.length) lines.push(`Mandates with no payments in this log: ${s.mandates_unused.join(", ")} (consider revoking unused authority).`, "");
  lines.push(
    "## What to do next",
    "",
    "1. Stop or recall BLOCK payments first; they had no valid authority.",
    "2. For REVIEW payments, get a named human to confirm or reject, and record the time.",
    "3. Fix the mandate or the agent's configuration so the same issue can't repeat.",
    "",
    "_Generated by Hyniqe Hub · Agent Payment Mandate Checker. Runs locally; no data leaves your machine. This is a control check, not legal or audit advice._",
  );
  return lines.join("\n") + "\n";
}

export function toResultCsv(r: CheckResult): string {
  return toCsv(
    r.payments.map((p) => ({
      line: p.line,
      payment_id: p.payment_id,
      timestamp: p.timestamp_raw,
      agent_id: p.agent_id,
      mandate_id: p.mandate?.id ?? "",
      payee: p.payee,
      amount: p.amount ?? "",
      currency: p.currency,
      verdict: p.verdict,
      audit_complete: p.audit_complete ? "yes" : "no",
      rules: p.findings.map((x) => x.rule).join(";"),
      details: p.findings.map((x) => x.message).join(" "),
    })),
    ["line", "payment_id", "timestamp", "agent_id", "mandate_id", "payee", "amount", "currency", "verdict", "audit_complete", "rules", "details"],
  );
}

function sevRank(s: string): number {
  return { critical: 0, high: 1, medium: 2, low: 3 }[s] ?? 4;
}
