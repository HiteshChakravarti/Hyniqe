import { mdTable, toCsv } from "../../shared/table.ts";
import type { DecodeResult, Field } from "./copybook.ts";

export function dictionaryMarkdown(fields: Field[], recordLength: number, warnings: string[], title = "Data dictionary"): string {
  const out = [`# ${title}`, "", `**Record length: ${recordLength} bytes** · ${fields.filter((f) => f.leaf).length} elementary fields.`, ""];
  if (warnings.length) out.push(...warnings.map((w) => `- ⚠️ ${w}`), "");
  out.push(mdTable(["Level", "Field", "Start", "Length", "Type", "PIC", "Storage", "Notes"], fields.map((f) => [
    f.level, "  ".repeat(Math.max(0, f.path.split(".").length - 1)) + f.name, f.offset + 1, f.length,
    f.kind === "numeric" ? `number${f.scale ? ` (${f.scale} decimals)` : ""}${f.signed ? ", signed" : ""}` : f.kind,
    f.pic || "-", f.usage === "COMP-3" ? "packed (COMP-3)" : f.usage === "BINARY" ? "binary" : f.kind === "group" ? "-" : "text/zoned",
    [f.redefines ? "redefines earlier field" : "", f.values.length ? `values: ${f.values.join("; ")}` : ""].filter(Boolean).join(" · "),
  ])), "");
  return out.join("\n") + "\n";
}

export function decodeSummary(d: DecodeResult): string {
  const out = ["## Decoded data", "", `**${d.records.toLocaleString("en-US")} records** decoded (${d.recordLength} bytes each).`];
  if (d.leftover) out.push(`⚠️ ${d.leftover} bytes left over at the end: record length or file format may be wrong (variable-length files need --rdw).`);
  if (d.problems.length) {
    out.push("", `⚠️ ${d.problems.length} field value(s) couldn't be decoded cleanly (shown as raw hex in the CSV):`, "", mdTable(["Record", "Field", "Problem", "Raw bytes"], d.problems.slice(0, 30).map((p) => [p.record, p.field, p.problem, p.raw])));
  }
  if (d.rows.length) out.push("", "**First 5 records**", "", mdTable(d.columns, d.rows.slice(0, 5)));
  out.push("", "_Generated by Hyniqe Hub · Copybook Decoder. Runs locally; your data never leaves your machine._");
  return out.join("\n") + "\n";
}

export function dictionaryCsv(fields: Field[]): string {
  return toCsv(fields.map((f) => ({ level: f.level, path: f.path, start: f.offset + 1, length: f.length, end: f.offset + f.length, type: f.kind, pic: f.pic, usage: f.usage, digits: f.digits, decimals: f.scale, signed: f.signed ? "yes" : "no", redefines: f.redefines ? "yes" : "no", values: f.values.join("; ") })),
    ["level", "path", "start", "length", "end", "type", "pic", "usage", "digits", "decimals", "signed", "redefines", "values"]);
}

export function dataCsv(d: DecodeResult): string {
  return toCsv(d.rows.map((r) => Object.fromEntries(d.columns.map((c, i) => [c, r[i]]))), d.columns);
}
