import type { Case } from "./investigate.ts";

export function toMarkdown(c: Case): string {
  const x = c.extracted;
  const icon = { URGENT: "🔴", HIGH: "🟠", NORMAL: "🟢" }[c.urgency];
  const out = [
    `# Payment investigation: ${c.info.title}`, "",
    `${icon} **Urgency: ${c.urgency}** · ${c.summary}`, "",
    "## What we found in the message", "",
    `- **UETR:** ${x.uetr ?? "❓ not found"}`,
    `- **Amount:** ${x.amounts.length ? x.amounts.map((a) => `${a.currency} ${a.amount.toLocaleString("en-US")}`).join(", ") : "❓ not found"}`,
    `- **Dates:** ${x.value_dates.join(", ") || "❓ not found"}`,
    `- **References:** ${x.references.join(", ") || "-"}`,
    `- **Banks (BIC):** ${x.bics.join(", ") || "-"}`,
    `- **Accounts (IBAN, valid):** ${x.ibans.join(", ") || "-"}`,
    `- **Beneficiary:** ${x.beneficiary ?? "-"}`,
    `- **Charges option:** ${x.charges_option ?? "-"}`, "",
  ];
  if (c.missing.length) out.push("## Ask the requester for", "", ...c.missing.map((m) => `- [ ] ${m}`), "");
  out.push("## Next steps", "", ...c.info.steps.map((s, i) => `${i + 1}. ${s}`), "");
  if (c.secondary.length) out.push(`_Also mentions: ${c.secondary.map((s) => s.replace(/_/g, " ").toLowerCase()).join(", ")}._`, "");
  out.push("## Draft reply to the other bank", "", ...c.draft_reply.split("\n\n").map((p) => p.split("\n").join("  \n")).flatMap((p) => [p, ""]));
  out.push("## Why it was classified this way", "", ...(c.evidence.length ? c.evidence.map((e) => `- ${e}`) : ["- No clear keywords: triage needed."]), "",
    "_Generated by Hyniqe Hub · Payment Investigation Assistant. Runs locally. Check the case type and draft before sending; amendment and recall requests must be verified through a trusted channel._");
  return out.join("\n") + "\n";
}
