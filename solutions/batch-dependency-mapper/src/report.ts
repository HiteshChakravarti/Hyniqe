import { mdTable, toCsv } from "../../shared/table.ts";
import type { Graph } from "./map.ts";

export function toMarkdown(g: Graph, skipped: string[] = [], title = "Batch dependency map"): string {
  const maxLevel = Math.max(0, ...g.levels.values());
  const out = [
    `# ${title}`, "",
    `**${g.jobs.length} jobs**, ${g.edges.length} dependencies, ${maxLevel + 1} stage(s) deep. ${g.externalInputs.length} external input(s), ${g.finalOutputs.length} final output(s).`, "",
  ];
  const problems: string[] = [];
  for (const m of g.missingConditions) problems.push(`🔴 **${m.job}** waits for condition \`${m.condition}\`, which no job sets: it will never start (or someone sets it by hand).`);
  for (const c of g.cycles) problems.push(`🔴 Circular dependency between: ${c.join(", ")}.`);
  for (const h of g.hubs.slice(0, 3)) problems.push(`🟠 **${h.job}** has ${h.dependents} job(s) downstream: if it fails or runs late, all of them are affected.`);
  for (const u of g.unusedConditions) problems.push(`🟡 ${u.job} sets condition \`${u.condition}\` that no job waits for (leftover, or a job outside these files).`);
  if (g.isolated.length) problems.push(`🟡 Not connected to anything in these files: ${g.isolated.join(", ")}.`);
  if (problems.length) out.push("## Risks", "", ...problems.map((p) => `- ${p}`), "");
  out.push("## Run order", "", mdTable(["Stage", "Job", "Schedule", "Runs", "Needs", "Produces"], [...g.jobs].sort((a, b) => (g.levels.get(a.name) ?? 0) - (g.levels.get(b.name) ?? 0)).map((j) => [
    (g.levels.get(j.name) ?? 0) < 0 ? "cycle" : (g.levels.get(j.name) ?? 0) + 1, j.name, j.schedule || "-", j.programs.slice(0, 4).join(", ") || "-",
    [...j.reads, ...[...j.inConds].map((c) => `⟨${c}⟩`)].slice(0, 6).join(", ") || "-", [...j.writes, ...[...j.outConds].map((c) => `⟨${c}⟩`)].slice(0, 6).join(", ") || "-",
  ])), "");
  if (g.edges.length) out.push("## Dependencies", "", mdTable(["From", "To", "Via"], g.edges.map((e) => [e.from, e.to, e.type === "condition" ? `condition ${e.via}` : e.type === "call" ? "runs it" : e.via])), "");
  if (g.externalInputs.length) out.push("## External inputs (produced outside these jobs)", "", ...g.externalInputs.map((d) => `- \`${d}\``), "");
  if (g.finalOutputs.length) out.push("## Final outputs (nothing here reads them)", "", ...g.finalOutputs.map((d) => `- \`${d}\``), "");
  if (skipped.length) out.push(`_Not recognised as JCL, cron, Control-M or shell: ${skipped.join(", ")}._`, "");
  out.push("```mermaid", mermaid(g), "```", "", "_Generated by Hyniqe Hub · Batch Dependency Mapper. Runs locally. Dependencies are inferred from the files given; jobs and feeds outside them show as external._");
  return out.join("\n") + "\n";
}

export function mermaid(g: Graph): string {
  const id = (n: string) => n.replace(/[^A-Za-z0-9_]/g, "_");
  const lines = ["flowchart LR", ...g.jobs.map((j) => `  ${id(j.name)}["${j.name}"]`)];
  const seen = new Set<string>();
  for (const e of g.edges) { const k = `${e.from}|${e.to}`; if (seen.has(k)) continue; seen.add(k); lines.push(`  ${id(e.from)} -->|${(e.type === "condition" ? e.via : e.type === "call" ? "runs" : e.via.split(/[\\/]/).pop() ?? "").replace(/[|"]/g, "")}| ${id(e.to)}`); }
  for (const m of g.missingConditions) lines.push(`  missing_${id(m.condition)}(["⚠ ${m.condition} never set"]) -.-> ${id(m.job)}`);
  return lines.join("\n");
}

/** Simple layered SVG: one column per stage. */
export function svg(g: Graph): string {
  const cols = new Map<number, string[]>();
  for (const j of g.jobs) { const l = g.levels.get(j.name) ?? 0; cols.set(l, [...(cols.get(l) ?? []), j.name]); }
  const levels = [...cols.keys()].sort((a, b) => a - b);
  const W = 170, H = 46, GX = 70, GY = 24;
  const pos = new Map<string, { x: number; y: number }>();
  levels.forEach((l, ci) => cols.get(l)!.forEach((n, ri) => pos.set(n, { x: 20 + ci * (W + GX), y: 20 + ri * (H + GY) })));
  const width = 40 + levels.length * (W + GX), height = 40 + Math.max(...[...cols.values()].map((c) => c.length)) * (H + GY);
  const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;");
  const bad = new Set(g.missingConditions.map((m) => m.job));
  const parts = [`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}" font-family="system-ui, sans-serif" font-size="12">`,
    `<defs><marker id="a" viewBox="0 0 10 10" refX="10" refY="5" markerWidth="7" markerHeight="7" orient="auto"><path d="M0,0L10,5L0,10z" fill="#7a8599"/></marker></defs>`];
  const seen = new Set<string>();
  for (const e of g.edges) {
    const a = pos.get(e.from), b = pos.get(e.to); const k = `${e.from}|${e.to}`;
    if (!a || !b || seen.has(k)) continue; seen.add(k);
    parts.push(`<path d="M${a.x + W},${a.y + H / 2} C${a.x + W + GX / 2},${a.y + H / 2} ${b.x - GX / 2},${b.y + H / 2} ${b.x},${b.y + H / 2}" fill="none" stroke="${e.type === "condition" ? "#8a63d2" : "#7a8599"}" stroke-width="1.4" ${e.type === "condition" ? 'stroke-dasharray="4 3"' : ""} marker-end="url(#a)"/>`);
  }
  for (const [n, p] of pos) parts.push(`<rect x="${p.x}" y="${p.y}" width="${W}" height="${H}" rx="8" fill="${bad.has(n) ? "#fde7e7" : "#eef2fb"}" stroke="${bad.has(n) ? "#c0392b" : "#4a6fd1"}"/><text x="${p.x + W / 2}" y="${p.y + H / 2 + 4}" text-anchor="middle" fill="#14213d">${esc(n.length > 24 ? n.slice(0, 23) + "…" : n)}</text>`);
  parts.push("</svg>");
  return parts.join("\n");
}

export function edgesCsv(g: Graph): string {
  return toCsv(g.edges as unknown as Record<string, unknown>[], ["from", "to", "via", "type"]);
}
