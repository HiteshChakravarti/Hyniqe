// Shared report styling and helpers. Reports are single self-contained HTML files that print well to PDF.

export function esc(s: unknown): string {
  return String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c] as string);
}

export function pct(n: number, d: number, digits = 1): string {
  return d ? `${((100 * n) / d).toFixed(digits)}%` : '–';
}

export function money(n: number, currency = ''): string {
  const s = n.toLocaleString('en-GB', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  return currency ? `${currency} ${s}` : s;
}

